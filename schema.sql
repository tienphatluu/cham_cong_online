-- Chạy toàn bộ SQL này trong Supabase Dashboard > SQL Editor > New query.
-- Bảng hồ sơ nhân viên
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  full_name text not null default '',
  role text not null default 'employee' check (role in ('admin', 'employee')),
  created_at timestamptz not null default now()
);

-- Bảng chấm công: mỗi nhân viên tối đa một bản ghi/ngày
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.profiles(id) on delete cascade,
  work_date date not null,
  clock_in timestamptz,
  clock_out timestamptz,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (employee_id, work_date),
  check (clock_out is null or clock_in is null or clock_out > clock_in)
);

create index if not exists attendance_work_date_idx on public.attendance(work_date);
create index if not exists attendance_employee_date_idx on public.attendance(employee_id, work_date);

alter table public.profiles enable row level security;
alter table public.attendance enable row level security;

-- Hàm kiểm tra quyền quản trị tránh policy tự tham chiếu bảng profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "profiles read self or admin" on public.profiles;
create policy "profiles read self or admin"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles update admin" on public.profiles;
create policy "profiles update admin"
on public.profiles for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "attendance read own or admin" on public.attendance;
create policy "attendance read own or admin"
on public.attendance for select to authenticated
using (employee_id = auth.uid() or public.is_admin());

drop policy if exists "attendance insert own or admin" on public.attendance;
create policy "attendance insert own or admin"
on public.attendance for insert to authenticated
with check (employee_id = auth.uid() or public.is_admin());

drop policy if exists "attendance update own or admin" on public.attendance;
create policy "attendance update own or admin"
on public.attendance for update to authenticated
using (employee_id = auth.uid() or public.is_admin())
with check (employee_id = auth.uid() or public.is_admin());

drop policy if exists "attendance delete admin" on public.attendance;
create policy "attendance delete admin"
on public.attendance for delete to authenticated
using (public.is_admin());

grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.attendance to authenticated;
grant usage, select on sequence public.attendance_id_seq to authenticated;

